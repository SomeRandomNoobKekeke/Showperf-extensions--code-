using HarmonyLib;
using System.Collections.Immutable;
using CursedUI;
using Microsoft.Xna.Framework;
using System.Reflection;

namespace ShowperfExtensions;

public partial class CodeExplorer
{
  private static BindingFlags Pls => BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance | BindingFlags.Static;
  private static bool IsTypeAutogenerated(Type T) => T.FullName.Contains('<');

  public abstract record Node(CodeExplorer explorer)
  {
    public CodeExplorer Explorer { get; } = explorer;

    public abstract Node GetParent();
    public abstract IEnumerable<Node> GetChildren();
    public abstract string NodeTypeName { get; }
  }

  public record AssemblyNode(CodeExplorer explorer) : Node(explorer)
  {
    public override Node GetParent() => this;
    public override IEnumerable<Node> GetChildren()
    {
      foreach (Type T in Explorer.TargetAssembly.GetTypes())
      {
        if (Explorer.FilterGeneratedStuff && IsTypeAutogenerated(T)) continue;
        yield return new TypeNode(Explorer, T);
      }
    }
    public override string NodeTypeName => "Assembly";
    public override string ToString() => Explorer.TargetAssembly.GetName().Name;
  }

  public record NamespaceNode(CodeExplorer explorer, string name) : Node(explorer)
  {
    public string Name { get; } = name;

    public override Node GetParent() => new AssemblyNode(Explorer);
    public override IEnumerable<Node> GetChildren()
    {
      foreach (Type T in Explorer.TargetAssembly.GetTypes())
      {
        if (Explorer.FilterGeneratedStuff && IsTypeAutogenerated(T)) continue;
        if (T.Namespace == Name) yield return new TypeNode(Explorer, T);
      }
    }
    public override string NodeTypeName => "Namespace";
    public override string ToString() => Name;
  }

  public record TypeNode(CodeExplorer explorer, Type type) : Node(explorer)
  {
    public Type Type { get; } = type;

    public override Node GetParent()
    {
      if (Type.DeclaringType is not null) return new TypeNode(Explorer, Type.DeclaringType);
      return new NamespaceNode(Explorer, Type.Namespace);
    }
    public override IEnumerable<Node> GetChildren()
    {
      foreach (Type nested in Type.GetNestedTypes(Pls))
      {
        if (Explorer.FilterGeneratedStuff && IsTypeAutogenerated(nested)) continue;
        yield return new TypeNode(Explorer, nested);
      }

      foreach (MethodBase mb in Type.GetMethods(Pls))
      {
        yield return new MethodNode(Explorer, mb);
      }
    }
    public override string NodeTypeName => "Type";
    public override string ToString() => Type.GetFullName();
  }

  public record MethodNode(CodeExplorer explorer, MethodBase method) : Node(explorer)
  {
    public MethodBase Method { get; } = method;

    public override Node GetParent()
    {
      return new TypeNode(Explorer, Method.DeclaringType);
    }
    public override IEnumerable<Node> GetChildren() => [];
    public override string NodeTypeName => "Method";
    public override string ToString() => Method.GetFullMethodName();
  }
}