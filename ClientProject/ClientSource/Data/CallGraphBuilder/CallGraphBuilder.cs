using System.Reflection;
using HarmonyLib;
using System.Text;
using System.Text.Json;
using CUILibs;

using Mono.Cecil;
using Mono.Cecil.Cil;

namespace ShowperfExtensions;

public class CallGraphBuilder
{
  public static BindingFlags Pls = BindingFlags.Instance | BindingFlags.Static | BindingFlags.Public | BindingFlags.NonPublic;


  public UltimateAssemblyAnalyzer3000 Analyzer => Plugin.Analyzer;


  private static bool IsTypeAutogenerated(Type T) => T.Name.StartsWith('<') || T.Name.StartsWith("__");
  private static bool IsMethodAutogenerated(MethodBase mb) => mb.IsSpecialName || mb.Name.StartsWith('<');

  public CallGraph ExtractFullCallGraph()
  {
    CallGraph callGraph = new CallGraph();

    foreach (Type T in Analyzer.BarotraumaAssembly.GetTypes())
    {
      if (IsTypeAutogenerated(T)) continue;

      foreach (MethodInfo mi in T.GetMethods(Pls))
      {
        if (IsMethodAutogenerated(mi)) continue;
        if (mi.DeclaringType != T) continue;

        CallGraph.Node node = new CallGraph.Node(mi)
        {
          CalledMethods = Analyzer.GetCalledMethods(mi).Where(m => !IsMethodAutogenerated(m)).ToList(),
        };

        callGraph[mi] = node;
      }
    }

    callGraph.Connect();

    return callGraph;
  }


  public CallGraph GetCallGraph(MethodBase method)
  {
    IEnumerable<MethodBase> calledMethods = Analyzer.GetCalledMethods(method);

    return new CallGraph()
    {
      [method] = new CallGraph.Node(method)
      {
        CalledMethods = calledMethods.Where(mb => !IsMethodAutogenerated(mb)).ToList()
      },
    };
  }



  public CallGraph GetCallGraph(Type T)
  {
    CallGraph info = new();

    foreach (MethodInfo mi in T.GetMethods(Pls))
    {
      if (IsMethodAutogenerated(mi)) continue;
      if (mi.DeclaringType != T) continue;
      if (mi.IsConstructor) continue;

      info[mi] = new CallGraph.Node(mi)
      {
        CalledMethods = Analyzer.GetCalledMethods(mi).Where(m => !IsMethodAutogenerated(m)).ToList()
      };
    }

    return info;
  }
}