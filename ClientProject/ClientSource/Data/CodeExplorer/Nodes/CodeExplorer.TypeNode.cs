using HarmonyLib;
using System.Collections.Immutable;
using CursedUI;
using Microsoft.Xna.Framework;
using System.Reflection;

namespace ShowperfExtensions;

public partial class CodeExplorer
{
  public record TypeNode(CodeExplorer explorer, Type type) : Node(explorer)
  {
    public Type Type { get; } = type;

    public override Node GetParent()
    {
      if (Type.DeclaringType is not null) return new TypeNode(Explorer, Type.DeclaringType);
      return new NamespaceNode(Explorer, Type.Namespace);
    }
    public override IEnumerable<Node> GetChildren()
    {
      foreach (Node node in GetNestedTypeNodes()) yield return node;
      foreach (Node node in GetMethodNodes()) yield return node;
      foreach (Node node in GetConstructorNodes()) yield return node;
    }


    public IEnumerable<Node> GetNestedTypeNodes()
    {
      foreach (Type nested in Type.GetNestedTypes(Pls))
      {
        if (Explorer.FilterAutogeneratedTypes && IsTypeAutogenerated(nested)) continue;

        yield return new TypeNode(Explorer, nested);
      }
    }

    public IEnumerable<Node> GetMethodNodes()
    {
      foreach (MethodInfo mi in Type.GetMethods(Pls))
      {
        if (Explorer.FilterAutogeneratedMethods && IsMethodAutogenerated(mi)) continue;
        if (Explorer.FilterInheritedMethods && mi.DeclaringType != Type) continue;
        if (mi.IsConstructor) continue;

        yield return new MethodNode(Explorer, mi);
      }
    }

    public IEnumerable<Node> GetConstructorNodes()
    {
      foreach (ConstructorInfo info in Type.GetConstructors(Pls))
      {
        yield return new ConstructorNode(Explorer, info);
      }
    }

    public override NodeType NodeType => NodeType.Type;
    public override string ToString() => Type.GetFullName();
  }
}