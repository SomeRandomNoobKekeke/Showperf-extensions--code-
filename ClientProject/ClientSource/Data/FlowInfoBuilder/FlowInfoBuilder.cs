using System.Reflection;
using HarmonyLib;
using System.Text;
using System.Text.Json;
using CUILibs;

using Mono.Cecil;
using Mono.Cecil.Cil;


namespace ShowperfExtensions;

public class FlowInfoBuilder
{
  public static BindingFlags Pls = BindingFlags.Instance | BindingFlags.Static | BindingFlags.Public | BindingFlags.NonPublic;


  public UltimateAssemblyAnalyzer3000 Analyzer => Mod.Analyzer;

  public FlowInfo GetFlowInfo(MethodBase method)
  {
    IEnumerable<MethodBase> calledMethods = Analyzer.GetCalledMethods(method);

    return new FlowInfo()
    {
      [method] = calledMethods.ToArray(),
    };
  }

  private static bool IsMethodAutogenerated(MethodBase mi) => mi.IsSpecialName || mi.Name.StartsWith('<');

  public FlowInfo GetFlowInfo(Type T)
  {
    FlowInfo info = new();

    foreach (MethodInfo mi in T.GetMethods(Pls))
    {
      if (IsMethodAutogenerated(mi)) continue;
      if (mi.DeclaringType != T) continue;
      if (mi.IsConstructor) continue;

      info[mi] = Analyzer.GetCalledMethods(mi).Where(m => !IsMethodAutogenerated(m)).ToArray();
    }

    return info;
  }

}