using HarmonyLib;
using System.Collections.Immutable;
using CursedUI;
using Microsoft.Xna.Framework;
using System.Reflection;

namespace ShowperfExtensions;

public partial class TypeExplorer
{
  public record NamespaceNode(TypeExplorer explorer, string name) : Node(explorer)
  {
    public string Name { get; } = name;

    public override Node GetParent() => new AssemblyNode(Explorer);
    public override IEnumerable<Node> GetChildren()
    {
      foreach (Type T in Explorer.TargetAssembly.GetTypes())
      {
        if (Explorer.FilterAutogeneratedTypes && IsTypeAutogenerated(T)) continue;
        if (T.Namespace == Name) yield return new TypeNode(Explorer, T);
      }
    }
    public override NodeType NodeType => NodeType.Namespace;
    public override string ToString() => Name;
  }
}