using HarmonyLib;
using System.Collections.Immutable;
using CursedUI;
using Microsoft.Xna.Framework;
using System.Reflection;

namespace ShowperfExtensions;

public partial class TypeExplorer
{
  public static BindingFlags Pls => BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance | BindingFlags.Static;
  private static bool IsTypeAutogenerated(Type T) => T.Name.StartsWith('<') || T.Name.StartsWith("__");
  private static bool IsMethodAutogenerated(MethodInfo mi) => mi.IsSpecialName || mi.Name.StartsWith('<');


  public Assembly TargetAssembly { get; set; }
  public Node Current { get; set; }

  public bool FilterAutogeneratedTypes { get; set; } = true;
  public bool FilterAutogeneratedMethods { get; set; } = true;
  public bool FilterInheritedMethods { get; set; } = true;

  public TypeExplorer(Assembly targetAssembly)
  {
    TargetAssembly = targetAssembly;
    Current = new AssemblyNode(this);
  }
}